    "function meoFindCardGroups(root){\n"
    "  var best=[];\n"
    "  var seen={};\n"
    "  function pushGroup(parent, items, scoreBonus){\n"
    "    if(!parent||!items||items.length<3) return;\n"
    "    var key='';\n"
    "    try{ key=meoCssPath(parent)+'|'+meoFp(items[0])+'|'+items.length; }catch(e){ key=String(items.length); }\n"
