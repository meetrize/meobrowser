    "    Array.from(parent.children).forEach(function(ch){\n"
    "      var fp=meoFp(ch);\n"
    "      if(!fp) return;\n"
    "      if(meoItemScore(ch)<2) return;\n"
    "      if(!groups[fp]) groups[fp]=[];\n"
