    "}\n"
    "function meoItemContentSignals(items){\n"
    "  var out={avgLen:0, shortRatio:0, uniqueHrefs:0, withTitle:0, withTime:0, withImg:0, withDesc:0, selfLink:0};\n"
    "  if(!items||!items.length) return out;\n"
