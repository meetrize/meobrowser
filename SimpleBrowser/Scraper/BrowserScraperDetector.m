    "      selector:meoStableSelFor(m.el, ['.load-more','button.load-more','[class*=\"load-more\"]','[class*=\"loadMore\"]']),\n"
    "      score:tier.loadMore + m.score,\n"
    "      reason:'Load More「'+meoNormText(m.el).slice(0,16)+'」',\n"
    "      pageDelayMs:900,\n"
    "      maxPages:80\n"
    "    });\n"
    "  }\n"
    "  if(pageGroup){\n"
    "    pageGroup.pageDelayMs=800;\n"
    "    pageGroup.maxPages=50;\n"
    "    pageGroup.score=(tier.pageNumbers + (pageGroup.score||0));\n"
    "    ranked.push(pageGroup);\n"
    "  }\n"
    "  if(infinite){\n"
    "    infinite.score=tier.infiniteScroll + (infinite.score||0);\n"
    "    ranked.push(infinite);\n"
    "  }\n"
    "  ranked.sort(function(a,b){ return (b.score||0)-(a.score||0); });\n"
    "  if(!ranked.length){\n"
    "    return { type:'none', selector:'', score:0, reason:'未发现翻页控件' };\n"
    "  }\n"
    "  return ranked[0];\n"
    "}\n";
}

+ (void)detectPaginationInWebView:(WKWebView *)webView
                 nearContainerPath:(NSString *)containerPath
                        completion:(void (^)(NSDictionary *pagination))completion {
    if (!webView) {
        if (completion) {
            completion(@{ @"type": @"none", @"selector": @"", @"score": @0, @"reason": @"无 WebView" });
        }
        return;
    }
    NSString *pathJSON = [self jsonStringLiteral:containerPath ?: @""];
    NSString *js = [NSString stringWithFormat:
                    @"(function(){\n%@\nreturn meoDetectPagination(%@);\n})();",
                    [self paginationHelpersJavaScript], pathJSON];
    [webView evaluateJavaScript:js completionHandler:^(id result, NSError *error) {
        (void)error;
        if ([result isKindOfClass:[NSDictionary class]]) {
            if (completion) completion((NSDictionary *)result);
            return;
        }
        if (completion) {
            completion(@{ @"type": @"none", @"selector": @"", @"score": @0, @"reason": @"翻页检测失败" });
        }
    }];
}

