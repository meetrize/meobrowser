    "      if(!byParent[pk]) byParent[pk]={parent:p, items:[]};\n"
    "      byParent[pk].items.push(el);\n"
    "    });\n"
    "    Object.keys(byParent).forEach(function(k){\n"
    "      var g=byParent[k];\n"
    "      pushGroup(g.parent, g.items, 20);\n"
    "    });\n"
    "  }catch(e){}\n"
    "  // Pass B：同构子节点扫描（提高上限，覆盖重 DOM 页面）\n"
    "  var nodes=(root||document).querySelectorAll('*');\n"
    "  var limit=Math.min(nodes.length, 5000);\n"
    "  for(var i=0;i<limit;i++){\n"
    "    var parent=nodes[i];\n"
    "    if(!parent||!parent.children||parent.children.length<3) continue;\n"
